# Loops are and essential part of programing. They allow you to repeat a block of code multiple times.
# There are two types of loops in python, "for" and "while"

# "for" loops
# the "for" loops is used to iterate over a sequence (list, tuple, string) or other iterable objects.




# let us iterate over a list
fruits = ["apple", "banana", "cherry"]

for fruit in fruits:
    print(fruit)

for i in range(10):
    print(i)

for i in range(7):
    print("world")

for char in "orembo":
    print(char)
    
