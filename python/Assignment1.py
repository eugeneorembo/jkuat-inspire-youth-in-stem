# User's score
score = 85

# Check the range and print the corresponding grade
if 90 <= score <= 100:
    grade = 'A'
elif 80 <= score <= 89:
    grade = 'B'
elif 70 <= score <= 79:
    grade = 'C'
elif 60 <= score <= 69:
    grade = 'D'
elif 50 <= score <= 59:
    grade = 'E'
elif 0 <= score <= 49:
    grade = 'F'


# Print the grade
print(f"The user's score is {score}. The grade is: {grade}")




